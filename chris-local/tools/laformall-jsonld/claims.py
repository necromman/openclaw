@dataclass
class Finding:
    field: str
    term: str
    group: str
    group_name: str
    suggestion: str

    def line(self) -> str:
        return f"[{self.field}] \"{self.term}\" - ({self.group}) {self.group_name} / 대체: {self.suggestion}"


def _scan_text(field: str, text: str) -> list[Finding]:
    found: list[Finding] = []
    if not text:
        return found
    low = text.replace(" ", "")
    seen: set[str] = set()
    for code, name, terms in GROUPS:
        for term, fix in terms:
            key = term.replace(" ", "")
            if key and key in low and term not in seen:
                seen.add(term)
                found.append(Finding(field, term, code, name, fix))
    nouns = [n for n in SYMPTOM_NOUNS if n in low]
    verbs = [v for v in EFFECT_VERBS if v in low]
    if nouns and verbs:
        combo = f"{nouns[0]}+{verbs[0]}"
        if combo not in seen:
            found.append(
                Finding(
                    field,
                    combo,
                    "가",
                    "질환 명사와 효과 동사 결합 (문장을 건너 붙어도 위반)",
                    "질환 명사를 지우고 물리 사양·사용 방법으로 다시 씁니다",
                )
            )
    return found


def check_fields(fields: dict[str, str]) -> list[Finding]:
    """{필드이름: 문자열} 을 받아 위반 목록을 낸다."""
    out: list[Finding] = []
    for name, value in fields.items():
        out.extend(_scan_text(name, value or ""))
    return out


def check_row(name: str, description: str) -> list[Finding]:
    return check_fields({"상품명": name, "설명": description})


def report_text(findings: list[Finding]) -> str:
    if not findings:
        return "규제 경고: 발견된 금지 표현 없음 (사전 (가)~(사) 검사)"
    lines = [f"규제 경고 - {len(findings)}건", ""]
    lines.extend(f.line() for f in findings)
    lines.append("")
    lines.append("허용 문안 예시:")
    lines.extend(f"  - {s}" for s in ALLOWED_EXAMPLES)
    lines.append("")
    lines.append(DISCLAIMER)
    return "\n".join(lines)


def draft_description(name: str, price: str = "", extra: str = "") -> str:
    """상품명 기반 설명 초안. 효능 표현을 쓰지 않고 사양·사용 안내로만 만든다."""
    base = (name or "라포르 제품").strip()
    if "베개" in base:
        body = (
            f"{base}. 머리와 목을 받쳐 편안한 수면 자세를 돕는 메모리폼 베개. "
            "경도 2종(레귤러 소프트·엑스트라 소프트) 선택, 14일 무료 경도 교환."
        )
    elif "커버" in base:
        body = f"{base}. 분리 세탁이 가능한 전용 커버. 본품과 같은 규격으로 맞춘 통기성 원단."
    elif "안대" in base:
        body = f"{base}. 눈 주변을 부드럽게 덮는 수면용 안대. 가벼운 착용감과 세탁 가능한 원단."
    elif "마사지" in base or "CST" in base.upper():
        body = (
            f"{base}. 목·어깨 부위에 사용하는 지압 방식 마사지기. "
            "하루 10분 사용 예시, 사용 부위와 방법 안내 제공."
        )
    elif "균형" in base or "척추" in base:
        body = f"{base}. 누운 자세에서 체압을 분산하도록 설계한 지지 기구. 사용 부위와 시간 안내 제공."
    else:
        body = f"{base}. 라포르 제품. 물리 사양과 사용 방법은 상세페이지 안내를 따릅니다."
    if extra:
        body = f"{body} {extra.strip()}"
    return re.sub(r"\s+", " ", body).strip()
