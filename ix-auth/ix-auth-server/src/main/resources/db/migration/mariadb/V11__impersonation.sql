-- 사용자 대리(impersonation) — 관리자가 특정 사용자로 전환한다.
--
-- V1~V10 은 고정이다. 이미 배포된 DB 가 그 체크섬을 들고 있으므로 고치면 부팅에 실패한다.


-- =====================================================================
-- 1. 대리 세션 표시 — sessions
-- =====================================================================

-- **토큰의 act 클레임을 세션 행이 들고 있어야 하는 이유.**
--
-- access token 은 15분마다 refresh 로 새로 발급된다. 회전 때 "이 세션은 누가 대리
-- 중인가" 를 다시 알 방법이 토큰밖에 없다면, 앱이 보내 준 값을 그대로 믿고 다시
-- 서명하는 꼴이 된다 — 그건 대리 사실을 클라이언트가 정할 수 있다는 뜻이다.
-- 세션 행에 못박아 두면 회전이 몇 번을 돌아도 act 의 출처가 서버로 남는다.
--
-- 두 컬럼 모두 NULL 이면 평범한 로그인 세션이다. 기존 행은 전부 그렇게 남는다.
ALTER TABLE sessions ADD COLUMN impersonator_id BIGINT;

-- 이메일을 함께 박아 두는 것은 **그 시점의 기록**이라서다. 관리자가 나중에 주소를
-- 바꾸거나 계정이 비활성이 되어도, 이 세션을 시작한 사람이 누구였는지는 변하지
-- 않아야 한다. 조인으로 지금 값을 끌어오면 과거의 사실이 현재에 따라 바뀐다.
ALTER TABLE sessions ADD COLUMN impersonator_email VARCHAR(320);

-- "이 관리자가 최근에 누구를 대리했나" 를 조사할 때 쓴다.
-- MariaDB 에는 부분 인덱스가 없어 전체 인덱스로 둔다 — 대부분 NULL 이라 비용은 작다
CREATE INDEX idx_sessions_impersonator ON sessions (impersonator_id);


-- =====================================================================
-- 2. 전용 권한 코드
-- =====================================================================

-- **ixauth:users:write 를 재사용하지 않는다.** 사용자를 고치는 것과 사용자가 되는
-- 것은 다른 일이다. users:write 는 비밀번호 초기화·2단계 초기화처럼 "관리자 자격으로"
-- 하는 조작이고 흔적이 관리자 이름으로 남지만, 대리는 그 사람 이름으로 남는다.
--
-- resource 를 users 가 아니라 impersonation 으로 둔 것도 같은 이유다 —
-- ixauth:users:* 를 준 역할이 대리 권한까지 딸려 갖는 일이 없어야 한다.
INSERT INTO permissions (code, domain, resource, action, description) VALUES
    ('ixauth:impersonation:create', 'ixauth', 'impersonation', 'create', '사용자 대리 시작');
