-- MySQL 8 방언 (mariadb/ 사본 — 다른 곳은 파일 안 주석으로 표시했다)
-- 로그인 수단 4종 — 매직 링크(G7) · Google(G8) · CAPTCHA(G11) · step-up 재인증(G18).
--
-- V1~V8 은 고정이다. 이미 배포된 DB 가 그 체크섬을 들고 있으므로 고치면 부팅에 실패한다.
--
-- =====================================================================
-- 이 마이그레이션은 DDL 이 없다. 그 사실 자체가 기록할 값어치가 있다.
-- =====================================================================
--
-- 네 기능 모두 기존 표를 그대로 쓴다. 왜 그런지를 남겨 두지 않으면 다음 사람이
-- "빠뜨린 것 아닌가" 를 의심하며 같은 조사를 반복한다.
--
--
-- ① 매직 링크 (G7) — verification_tokens 를 그대로 쓴다
--
--    purpose 에 'MAGIC_LINK'(10자) 가 하나 늘어난다. 컬럼은 VARCHAR(20) 이고
--    CHECK 제약이 없으므로(V2) 값을 넣기 위해 고칠 것이 없다.
--
--    표를 따로 만들지 않은 이유는 V2 가 정한 것과 같다 — 만료·1회용·자동 정리 규칙이
--    두 벌로 갈라지면 그중 하나만 고치는 실수가 나고, 그 하나가 곧 구멍이 된다.
--    매직 링크는 그 규칙이 **가장 엄격하게** 지켜져야 하는 용도라 더욱 그렇다:
--    이 토큰은 재설정 링크와 달리 그 자체가 로그인이다.
--
--    조회 경로도 기존 인덱스로 전부 덮인다.
--      · 링크 확인      → uq_verification_token (token_hash)
--      · 재발송 쿨다운  → idx_verification_user_purpose (user_id, purpose)
--      · 만료분 정리    → idx_verification_expires (expires_at)
--
--    수명은 account.magic-link-token-ttl(기본 10분)이고 DB 가 아니라 설정이 정한다.
--    스키마에 박아 두면 고객사마다 jar 를 다시 빌드해야 한다.
--
--
-- ② Google 로그인 (G8) — identities 를 그대로 쓴다
--
--    provider 에 'GOOGLE'(6자) 이 하나 늘어난다. VARCHAR(20) · CHECK 없음(V3).
--    subject 는 Google 의 sub(21자리 숫자)라 VARCHAR(255) 안에 충분히 들어간다.
--
--    PKCE 를 쓰지만 oauth_states.code_verifier 도 손대지 않는다 — 우리가 만드는
--    verifier 는 88자(랜덤 64바이트의 base64url)이고 컬럼은 VARCHAR(128) 이다.
--    RFC 7636 이 허용하는 상한(128자)과도 맞는다.
--
--
-- ③ CAPTCHA (G11) — 저장할 것이 없다
--
--    토큰은 요청 한 건 안에서 provider 에게 물어보고 버린다. 남겨 두면 우리가
--    "이 사용자가 봇 같았다" 는 판정 이력을 갖게 되는데, 그건 우리 판단도 아니고
--    보관할 근거도 없는 개인정보다.
--
--    실패도 남기지 않는다. 감사 로그에 남기고 싶어질 수 있지만, 실패의 대부분은
--    공격이 아니라 오래된 브라우저·확장 프로그램·네트워크 차단이다. 그것을 사람마다
--    쌓아 두면 로그가 소음으로 덮이고 진짜 신호가 묻힌다. 지금은 WARN 로그로 족하다.
--
--
-- ④ step-up 재인증 (G18) — mfa_credentials 를 그대로 쓴다
--
--    코드 검증은 로그인 2단계와 **같은 경로**를 지난다(MfaService.consumeTotp).
--    그래서 재사용 차단(last_step)과 백업 코드 소모(backup_codes_hash)가 저절로
--    같이 적용된다. 여기서 따로 구현했다면 그 두 장치를 두 벌로 갈라 놓았을 것이다.
--
--    "언제 재인증했는가" 를 따로 저장하지 않는다 — 유효 시간(grace)을 두면 그 사이
--    비밀번호 변경·이메일 변경이 코드 없이 통과한다. 매번 받는 편이 단순하고 안전하다.
--    기록은 감사 로그(MFA_VERIFIED, detail.phase = STEP_UP)에 남는다.
--
--
-- =====================================================================
-- 기존 사용자에게 미치는 영향: 없다
-- =====================================================================
--
-- 새 설정의 기본값이 전부 "지금까지와 똑같이 동작" 이다.
--   account.magic-link-enabled = false   (요청하면 403)
--   social.google.enabled      = false   (provider 목록에 나오지 않는다)
--   captcha.enabled            = false   (captchaToken 을 보내지 않아도 그대로 통과)
--   mfa.step-up-actions        = (비움)  (mfaCode 를 보내지 않아도 그대로 통과)
--
-- 켜는 것은 운영자의 선택이고, 켜기 전에 앱을 먼저 고쳐야 하는 것(captcha·step-up)은
-- 설정 화면의 경고에 적혀 있다.
